def ensure_dir(path: str) -> None:
    if not os.path.exists(path):
        os.makedirs(path, exist_ok=True)


def generate_soft_noise_image(path: str, size: Tuple[int, int] = (1600, 900), seed: int = 1) -> None:
    rng = np.random.default_rng(seed)
    # Create a low-res random field and upscale for a soft gradient-like look
    low_w, low_h = 64, 36
    low = rng.random((low_h, low_w, 3), dtype=np.float32)
    # Apply a simple channel-wise palette boost for vibrance
    palette = np.array([1.3, 1.1, 1.25], dtype=np.float32)  # R, G, B multipliers
    low = np.clip(low * palette, 0.0, 1.0)
    arr = (low * 255).astype(np.uint8)
    img = Image.fromarray(arr, mode='RGB').resize(size, resample=Image.BICUBIC)
    img = img.filter(ImageFilter.GaussianBlur(radius=1.2))
    img.save(path, format='PNG')


def generate_low_poly_image(path: str, size: Tuple[int, int] = (1600, 900), seed: int = 2, num_triangles: int = 220) -> None:
    rng = np.random.default_rng(seed)
    img = Image.new('RGB', size, (255, 255, 255))
    draw = ImageDraw.Draw(img)
    w, h = size

    def random_color() -> Tuple[int, int, int]:
        base = np.array([rng.integers(0, 256), rng.integers(0, 256), rng.integers(0, 256)], dtype=np.int32)
        # Slight pastel shift
        pastel = (base + 255) // 2
        return tuple(int(x) for x in pastel)

    for _ in range(num_triangles):
        pts = [
            (int(rng.integers(-w * 0.1, int(w * 1.1))), int(rng.integers(-h * 0.1, int(h * 1.1)))),
            (int(rng.integers(-w * 0.1, int(w * 1.1))), int(rng.integers(-h * 0.1, int(h * 1.1)))),
            (int(rng.integers(-w * 0.1, int(w * 1.1))), int(rng.integers(-h * 0.1, int(h * 1.1)))),
        ]
        draw.polygon(pts, fill=random_color())

    img = img.filter(ImageFilter.GaussianBlur(radius=0.8))
    img.save(path, format='PNG')


def generate_wave_image(path: str, size: Tuple[int, int] = (1600, 900), seed: int = 3) -> None:
    rng = np.random.default_rng(seed)
    w, h = size
    y = np.linspace(0, math.pi * 2, h).reshape(h, 1)
    x = np.linspace(0, math.pi * 2, w).reshape(1, w)

    # Random frequencies and phases for each channel
    fx = rng.uniform(1.5, 3.5, size=3)
    fy = rng.uniform(1.0, 2.5, size=3)
    ph = rng.uniform(0, math.pi * 2, size=3)

    channels = []
    for c in range(3):
        grid = np.sin(fx[c] * x + ph[c]) * np.cos(fy[c] * y - ph[c])
        grid = (grid - grid.min()) / (grid.max() - grid.min() + 1e-9)
        channels.append(grid)

    arr = np.stack(channels, axis=-1)
    arr = (arr * 255).astype(np.uint8)
    img = Image.fromarray(arr, mode='RGB')
    img = img.filter(ImageFilter.GaussianBlur(radius=0.6))
    img.save(path, format='PNG')


def mm(val: float) -> float:
    # Helper to convert mm to points if needed (1 inch = 25.4 mm, reportlab uses points)
    return val * inch / 25.4


def build_pdf(output_path: str, image_paths: List[str]) -> None:
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'TitleLarge', parent=styles['Title'], fontSize=28, leading=32, alignment=TA_LEFT, spaceAfter=12
    )
    h_style = ParagraphStyle(
        'Heading', parent=styles['Heading2'], fontSize=16, leading=20, spaceBefore=10, spaceAfter=6
    )
    normal_style = ParagraphStyle(
        'NormalTight', parent=styles['BodyText'], fontSize=11, leading=15, spaceAfter=6
    )
    bullet_style = ParagraphStyle(
        'Bullet', parent=styles['BodyText'], fontSize=11, leading=15, leftIndent=14, spaceBefore=2, spaceAfter=2
    )

    doc = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        title='English Tutor: 10 Mixed-Skills Exercises',
        author='Auto-generated by AI',
        leftMargin=inch,
        rightMargin=inch,
        topMargin=inch,
        bottomMargin=inch,
    )

    story: List = []

    # Cover
    story.append(Paragraph('English Tutor: 10 Mixed-Skills Exercises', title_style))
    story.append(Paragraph('Speaking • Grammar • Vocabulary • Reading', normal_style))
    story.append(Spacer(1, 8))

    if image_paths:
        cover_img = RLImage(image_paths[0], width=doc.width, height=doc.width * 9 / 16)
        story.append(cover_img)
    story.append(Spacer(1, 14))
    story.append(Paragraph('This resource contains 10 classroom-ready activities for intermediate learners (B1–B2).', normal_style))
    story.append(PageBreak())

    # Exercise 1: Speaking – Warm-up
    story.append(Paragraph('Exercise 1: Speaking – Warm-up Conversation', h_style))
    story.append(Paragraph('Discuss with a partner. Take turns asking and answering:', normal_style))
    story.append(ListFlowable([
        ListItem(Paragraph('What is an app or tool you use every day? Why do you like it?', bullet_style)),
        ListItem(Paragraph('Describe the last time technology saved you time.', bullet_style)),
        ListItem(Paragraph('Which technology trend do you find most exciting or worrying?', bullet_style)),
    ], bulletType='bullet', start='circle'))

    # Exercise 2: Speaking – Photo description with AI image
    story.append(Spacer(1, 8))
    story.append(Paragraph('Exercise 2: Speaking – Describe the Picture', h_style))
    if len(image_paths) >= 2:
        story.append(RLImage(image_paths[1], width=doc.width, height=doc.width * 9 / 16))
        story.append(Spacer(1, 6))
    story.append(Paragraph('Describe what you see. Then, predict what happened just before and what might happen next.', normal_style))
    story.append(ListFlowable([
        ListItem(Paragraph('People/objects: What stands out? Use adjectives for color, shape, mood.', bullet_style)),
        ListItem(Paragraph('Setting: Where and when is this? Give evidence from the image.', bullet_style)),
        ListItem(Paragraph('Story: Create a short narrative (5–6 sentences).', bullet_style)),
    ], bulletType='bullet', start='circle'))

    # Exercise 3: Speaking – Role-play
    story.append(Spacer(1, 8))
    story.append(Paragraph('Exercise 3: Speaking – Role-play: Hotel Check-in', h_style))
    story.append(Paragraph('Student A: You are the receptionist. Student B: You are a tired traveler whose reservation cannot be found.', normal_style))
    story.append(ListFlowable([
        ListItem(Paragraph('Clarify the name, dates, and room type.', bullet_style)),
        ListItem(Paragraph('Offer two solutions. Ask for preferences politely.', bullet_style)),
        ListItem(Paragraph('End the conversation positively.', bullet_style)),
    ], bulletType='bullet', start='circle'))

    # Exercise 4: Grammar – Present Perfect vs Past Simple
    story.append(PageBreak())
    story.append(Paragraph('Exercise 4: Grammar – Present Perfect vs. Past Simple', h_style))
    story.append(Paragraph('Complete with the correct tense. Use the verb in parentheses.', normal_style))
    sentences_4 = [
        'I (be) to London three times.',
        'She (finish) her report yesterday.',
        'We (not see) him since June.',
        'They (move) to this city in 2019.',
        'He (just/call) you. Did you miss it?',
        'My team (win) the match last weekend.',
        'I (never/try) rock climbing.',
        'The movie (start) at 8 p.m.',
        'She (live) here for five years.',
        'We (meet) at the conference in 2022.',
    ]
    story.append(ListFlowable([ListItem(Paragraph(f'{i+1}. {s}', normal_style)) for i, s in enumerate(sentences_4)], bulletType='1'))

    # Exercise 5: Grammar – Articles (a/an/the/Ø)
    story.append(Spacer(1, 8))
    story.append(Paragraph('Exercise 5: Grammar – Articles (a/an/the/Ø)', h_style))
    story.append(Paragraph('Insert a/an/the or Ø (no article).', normal_style))
    sentences_5 = [
        '___ internet has changed the way we work.',
        'I bought ___ umbrella and ___ pair of boots.',
        'She is ___ engineer who loves solving problems.',
        'We went to ___ best restaurant in town.',
        '___ coffee I had this morning was too strong.',
        'Do you play ___ piano?',
        'He became ___ CEO after years of hard work.',
        '___ Mount Everest is the highest mountain.',
        'I usually take ___ bus to work.',
        'She studied at ___ university in Paris.',
    ]
    story.append(ListFlowable([ListItem(Paragraph(f'{i+1}. {s}', normal_style)) for i, s in enumerate(sentences_5)], bulletType='1'))

    # Exercise 6: Grammar – Second Conditional
    story.append(Spacer(1, 8))
    story.append(Paragraph('Exercise 6: Grammar – Second Conditional', h_style))
    story.append(Paragraph("Rewrite using the second conditional (would + base, if + past simple).", normal_style))
    sentences_6 = [
        'I do not have enough time. I cannot start a new hobby.',
        'She cannot drive. She does not visit distant places.',
        'They do not know the answer. They cannot help us.',
        'The office is noisy. We cannot concentrate.',
        'He does not speak French. He cannot work in Paris.',
    ]
    story.append(ListFlowable([ListItem(Paragraph(f'{i+1}. {s}', normal_style)) for i, s in enumerate(sentences_6)], bulletType='1'))

    # Exercise 7: Vocabulary – Phrasal Verbs
    story.append(PageBreak())
    story.append(Paragraph('Exercise 7: Vocabulary – Phrasal Verbs (Match)', h_style))
    story.append(Paragraph('Match A with B.', normal_style))
    left_list_7 = [
        'A. look up',
        'B. put off',
        'C. get along (with)',
        'D. run out (of)',
        'E. figure out',
        'F. take up',
    ]
    right_list_7 = [
        '1. postpone',
        '2. search for information',
        '3. start a new activity',
        '4. understand/solve',
        '5. have a friendly relationship',
        '6. have none left',
    ]
    story.append(Paragraph('A:', normal_style))
    story.append(ListFlowable([ListItem(Paragraph(item, normal_style)) for item in left_list_7], bulletType='a'))
    story.append(Paragraph('B:', normal_style))
    story.append(ListFlowable([ListItem(Paragraph(item, normal_style)) for item in right_list_7], bulletType='1'))

    # Exercise 8: Vocabulary – Collocations
    story.append(Spacer(1, 8))
    story.append(Paragraph('Exercise 8: Vocabulary – Collocations with make/do/take/have', h_style))
    story.append(Paragraph('Complete with the correct verb: make, do, take, or have.', normal_style))
    sentences_8 = [
        '___ a decision about your next course.',
        '___ progress even if it is slow.',
        '___ a break every 60 minutes.',
        '___ an effort to speak English daily.',
        '___ responsibility for the result.',
        '___ notes during the meeting.',
        '___ a mistake and learn from it.',
        '___ fun while you study.',
    ]
    story.append(ListFlowable([ListItem(Paragraph(f'{i+1}. {s}', normal_style)) for i, s in enumerate(sentences_8)], bulletType='1'))

    # Exercise 9: Reading – Digital Detox
    story.append(PageBreak())
    story.append(Paragraph('Exercise 9: Reading – Digital Detox', h_style))
    if len(image_paths) >= 3:
        story.append(RLImage(image_paths[2], width=doc.width, height=doc.width * 9 / 16))
        story.append(Spacer(1, 6))
    passage_9 = (
        "Many people reach for their phones before they even get out of bed. A short check quickly becomes half an hour of scrolling. "
        "A digital detox does not mean throwing your phone away; it means setting healthy limits. For one week, try switching off all "
        "non‑essential notifications, placing your phone in another room while you sleep, and choosing specific times to check messages. "
        "After a few days, most people report better sleep, more focus, and calmer mornings. Technology is a great servant, but a poor master."
    )
    story.append(Paragraph(passage_9, normal_style))
    questions_9 = [
        '1) What is the main purpose of a digital detox?',
        '2) Name two actions suggested in the text.',
        '3) What benefits do people usually notice after a few days?',
        '4) Explain the meaning of: "Technology is a great servant, but a poor master."',
        '5) Do you think you need a digital detox? Why or why not?',
    ]
    story.append(ListFlowable([ListItem(Paragraph(q, normal_style)) for q in questions_9], bulletType='1'))

    # Exercise 10: Reading – Short Story
    story.append(Spacer(1, 8))
    story.append(Paragraph('Exercise 10: Reading – Short Story', h_style))
    passage_10 = (
        "When Maya got off the bus, she noticed a small leather wallet on the seat. Inside, there was no cash, just a photo of a smiling family, "
        "a train ticket, and a student card with the name ‘Leo Martin’. The last bus was leaving, and the ticket showed a departure in 40 minutes. "
        "Maya hesitated, then asked the driver for help. Together, they called the number on the card. Ten minutes later, a breathless boy ran up. "
        "He thanked Maya again and again, explaining that the ticket was for a scholarship interview. The bus driver smiled as the two hurried away."
    )
    story.append(Paragraph(passage_10, normal_style))
    questions_10 = [
        '1) Why was the wallet important to Leo?',
        '2) How did Maya decide what to do?',
        '3) What details helped Maya contact the owner?',
        '4) What does the story suggest about Maya’s character?',
        '5) Imagine the interview. Write two questions the panel might ask Leo.',
    ]
    story.append(ListFlowable([ListItem(Paragraph(q, normal_style)) for q in questions_10], bulletType='1'))

    # Build
    doc.build(story)


